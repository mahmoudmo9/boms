"""Write backend/requirements.lock: exact pins of every runtime package BOMS needs on Windows (win_amd64, CPython 3.12).

Run from the repository root with the dev venv's Python (it has every Linux-side package installed):

    .venv/bin/python scripts/lock_windows.py

Environment markers are evaluated for Windows, so Windows-only dependencies (pywin32-ctypes,
colorama, tzdata, ...) are included and Linux-only ones (SecretStorage, jeepney, ...) are not.
Versions come from the local venv when installed there, otherwise the newest release on PyPI.
"""

import json
import re
import sys
import tomllib
import urllib.request
from importlib import metadata
from pathlib import Path

from packaging.markers import Marker
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
WINDOWS_ENV = {
    "os_name": "nt",
    "sys_platform": "win32",
    "platform_system": "Windows",
    "platform_machine": "AMD64",
    "platform_release": "10",
    "platform_version": "10.0.19045",
    "python_version": "3.12",
    "python_full_version": "3.12.10",
    "implementation_name": "cpython",
    "platform_python_implementation": "CPython",
}


def marker_ok(marker: Marker | None, extras: set[str]) -> bool:
    if marker is None:
        return True
    return any(marker.evaluate({**WINDOWS_ENV, "extra": e}) for e in (extras or {""}))


def pypi_info(name: str) -> tuple[str, list[str]]:
    with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/json", timeout=30) as resp:
        info = json.load(resp)["info"]
    return info["version"], info.get("requires_dist") or []


def lookup(name: str) -> tuple[str, list[str]]:
    try:
        dist = metadata.distribution(name)
        return dist.version, dist.requires or []
    except metadata.PackageNotFoundError:
        return pypi_info(name)


def main() -> None:
    project = tomllib.loads((ROOT / "backend" / "pyproject.toml").read_text())["project"]
    queue = [Requirement(r) for r in project["dependencies"]]
    pins: dict[str, tuple[str, str]] = {}
    extras_seen: dict[str, set[str]] = {}
    while queue:
        req = queue.pop()
        if not marker_ok(req.marker, set()):
            continue
        key = canonicalize_name(req.name)
        new_extras = set(req.extras) - extras_seen.get(key, set())
        if key in pins and not new_extras:
            continue
        extras_seen.setdefault(key, set()).update(req.extras)
        version, requires = lookup(req.name)
        if not req.specifier.contains(version, prereleases=True):
            sys.exit(f"{req.name} {version} does not satisfy {req}")
        pins[key] = (req.name, version)
        for raw in requires:
            child = Requirement(raw)
            if marker_ok(child.marker, extras_seen[key]):
                child.marker = None  # evaluated here, with this package's extras
                queue.append(child)

    lines = [
        "# Runtime packages for Windows (win_amd64, CPython 3.12). Generated by scripts/lock_windows.py.",
        "# The release wheelhouse contains exactly these wheels; install.ps1 installs them offline.",
    ]
    lines += [f"{name}=={version}" for name, version in sorted(pins.values(), key=lambda p: p[0].lower())]
    out = ROOT / "backend" / "requirements.lock"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(pins)} packages)")


if __name__ == "__main__":
    if not re.match(r"3\.12", sys.version):
        print("warning: run this with Python 3.12 so local versions match the target", file=sys.stderr)
    main()
